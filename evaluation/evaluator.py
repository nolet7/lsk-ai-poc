"""
FILE PURPOSE: Workflow Output Evaluator

This file evaluates the result returned by the Production AI Platform's
LangGraph workflow.

The evaluator performs lightweight deterministic checks to confirm that:

1. Enterprise research sources were retrieved.
2. The final report contains recommendations.
3. The Reviewer Agent produced review notes.
4. The final report contains enough detail.
5. The result meets the minimum passing score.

Workflow position:

FastAPI POST /run
    -> LangGraph multi-agent workflow
    -> evaluate_output()
    -> Evaluation results returned to API client

Important correction:
The original code searched for the words "Reviewer Notes" inside the final
report. However, reviewer feedback is stored separately in
result["review_notes"], so the review check now validates that state field.
"""


def evaluate_output(result: dict) -> dict:
    """
    Evaluate the completed multi-agent workflow result.

    Args:
        result:
            Final LangGraph state containing the report, research context,
            reviewer feedback, and other workflow fields.

    Returns:
        A dictionary containing individual binary scores, total score,
        maximum score, percentage, and pass/fail status.
    """

    # Read the approved report generated by the Writer and Reviewer Agents.
    # .get() prevents a KeyError if the workflow returns an incomplete result.
    report = result.get("final_report", "")

    # Read the enterprise evidence retrieved by the Researcher Agent.
    context = result.get("research_context", [])

    # Read reviewer feedback from shared state.
    # The original evaluator incorrectly searched for "Reviewer Notes"
    # inside the final report instead of checking this separate field.
    review_notes = result.get("review_notes", "")

    # Create one binary score for each quality requirement.
    # A score of 1 means the check passed; 0 means it failed.
    scores = {
        # Pass when at least one enterprise source was retrieved.
        "has_sources": 1 if len(context) > 0 else 0,

        # Pass when the final report includes a recommendations section.
        "has_recommendations": (
            1 if "Recommendations" in report else 0
        ),

        # Pass when the Reviewer Agent produced non-empty review feedback.
        "has_review": 1 if bool(review_notes.strip()) else 0,

        # Pass when the final report contains more than 500 characters.
        "length_score": 1 if len(report) > 500 else 0,
    }

    # Add all binary quality scores.
    total = sum(scores.values())

    # Count the maximum number of points available.
    max_score = len(scores)

    # Convert the total score into a percentage.
    # The guard prevents division by zero if all checks are removed later.
    percentage = (
        round((total / max_score) * 100, 2)
        if max_score > 0
        else 0.0
    )

    # Return the complete evaluation result to the FastAPI application.
    return {
        # Show the result of each individual quality check.
        "scores": scores,

        # Show the number of checks that passed.
        "total_score": total,

        # Show the maximum possible score.
        "max_score": max_score,

        # Show the score as a percentage.
        "percentage": percentage,

        # Require at least three of the four checks to pass.
        "passed": total >= 3,
    }
